// Package pkgdoc 提供仓库级的包文档自检。
//
// 包文档是读者进入一个包的第一读物，也是 go doc 与 pkg.go.dev 的入口。
// 本包只提供测试：它遍历仓库里的每一个 Go 包，检查包文档是否符合 Go 惯例，
// 并扫出"文件路径横幅"这类误插入的注释。
//
// 检查项：
//   - 一个包恰好有一个文件带包注释：多个会被 go/doc 按文件名序拼成重复段落，
//     一个都没有则读者在 godoc 里看不到任何说明；
//   - 包文档首行以 "Package <包名> " 开头（main 包用 "Command <命令名> "）；
//   - 源码注释里不含"整行只有一个文件路径"的横幅。
//
// 为什么需要这条守卫：路径横幅紧挨 package 条款时会被当成包文档，
// go doc 的首行就变成一条内部路径。这类事故不改变任何运行行为，
// 功能测试发现不了，只能靠静态检查拦住。
